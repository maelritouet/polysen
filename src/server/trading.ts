import Decimal from "decimal.js";
import { and, eq } from "drizzle-orm";
import { displayPercent, quoteBuy, quoteSell, SHARE_DECIMALS, type Pool, type Side } from "@/core/amm";
import { canSpend } from "@/core/ledger";
import { D, decimalToCoinsDown, type Coins, type Dec } from "@/core/money";
import type { Db, Tx } from "@/db/client";
import { ledger, markets, positions, profiles, trades } from "@/db/schema";
import { UserError, uniqueViolation } from "./errors";
import { getBalance } from "./wallet";

/** Smallest bet: 1 coin (decision 008). */
export const MIN_BET: Coins = 100n;

export interface BuyInput {
  marketId: string;
  side: Side;
  /** Hundredths. */
  coins: Coins;
  /** Generated by the client once per confirm: a retry with the same id does nothing new. */
  requestId: string;
}

export interface SellInput {
  marketId: string;
  side: Side;
  /** A share count (up to 12 decimals), or "all" for exactly what is held. */
  shares: string;
  requestId: string;
}

export interface TradeResult {
  shares: Dec;
  /** Hundredths paid (buy) or received (sell). */
  coins: Coins;
  /** YES probability after the trade, as shown (1–99). */
  percentAfter: number;
}

const poolOf = (m: { poolYes: string; poolNo: string }): Pool => ({ yes: D(m.poolYes), no: D(m.poolNo) });

/**
 * Locks the market, then the member: the same order everywhere (cancels lock
 * the market, then players in id order), so trades can't deadlock. Trades on
 * one market run one at a time, each seeing the pool the previous one left.
 */
async function lockForTrade(tx: Tx, marketId: string, memberId: string) {
  const [m] = await tx.select().from(markets).where(eq(markets.id, marketId)).for("update");
  if (!m) throw new UserError("Marché introuvable.");
  const [me] = await tx.select({ suspendedAt: profiles.suspendedAt }).from(profiles).where(eq(profiles.id, memberId)).for("update");
  if (!me) throw new UserError("Profil introuvable.");
  if (me.suspendedAt) throw new UserError("Ton compte est suspendu.");
  return m;
}

function checkOpen(m: typeof markets.$inferSelect, now: Date) {
  if (m.status !== "open") throw new UserError("Ce marché n'est pas ouvert aux paris.");
  if (m.closeAt <= now) throw new UserError("Ce marché est fermé : plus de paris possibles.");
}

/** A trade already written under this request id, replayed as its result. */
async function replayed(tx: Tx, requestId: string, memberId: string, kind: "buy" | "sell"): Promise<TradeResult | null> {
  const [r] = await tx.select().from(trades).where(eq(trades.requestId, requestId));
  if (!r) return null;
  if (r.memberId !== memberId || r.kind !== kind) throw new UserError("Requête invalide.");
  const percentAfter = Math.min(99, Math.max(1, D(r.probAfter).mul(100).toDecimalPlaces(0, Decimal.ROUND_HALF_UP).toNumber()));
  return { shares: D(r.shares), coins: r.coins, percentAfter };
}

/**
 * Runs a trade transaction. If a copy of the same request committed first and
 * this one hits the unique request_id, the original result is returned.
 */
async function withReplay(
  db: Db,
  requestId: string,
  memberId: string,
  kind: "buy" | "sell",
  run: (tx: Tx) => Promise<TradeResult>,
): Promise<TradeResult> {
  try {
    return await db.transaction(run);
  } catch (err) {
    if (uniqueViolation(err) !== null) {
      const again = await db.transaction((tx) => replayed(tx, requestId, memberId, kind));
      if (again) return again;
    }
    throw err;
  }
}

/** Places a bet: coins in, shares out, the pool moves. All or nothing. */
export async function buy(db: Db, memberId: string, input: BuyInput, now: Date = new Date()): Promise<TradeResult> {
  if (input.coins < MIN_BET) throw new UserError("La mise minimum est de 1 pièce.");
  return withReplay(db, input.requestId, memberId, "buy", async (tx) => {
    const m = await lockForTrade(tx, input.marketId, memberId);
    // Checked under the locks: a copy of this request that got here first has committed.
    const done = await replayed(tx, input.requestId, memberId, "buy");
    if (done) return done;
    checkOpen(m, now);
    if (!canSpend(await getBalance(tx, memberId), input.coins)) throw new UserError("Tu n'as pas assez de pièces.");

    let q;
    try {
      q = quoteBuy(poolOf(m), input.side, input.coins);
    } catch {
      throw new UserError("Ce pari est trop gros pour ce marché.");
    }
    await tx.insert(trades).values({
      marketId: m.id,
      memberId,
      side: input.side,
      kind: "buy",
      coins: input.coins,
      shares: q.shares.toFixed(SHARE_DECIMALS),
      probBefore: q.probBefore.toFixed(12),
      probAfter: q.probAfter.toFixed(12),
      requestId: input.requestId,
    });
    await tx.insert(ledger).values({ memberId, amount: -input.coins, reason: "bet", marketId: m.id, requestId: input.requestId });
    await tx
      .update(markets)
      .set({ poolYes: q.pool.yes.toFixed(SHARE_DECIMALS), poolNo: q.pool.no.toFixed(SHARE_DECIMALS) })
      .where(eq(markets.id, m.id));
    return { shares: q.shares, coins: input.coins, percentAfter: displayPercent(q.pool) };
  });
}

export async function heldShares(db: Db | Tx, marketId: string, memberId: string, side: Side): Promise<Dec> {
  const [p] = await db
    .select({ yes: positions.yes, no: positions.no })
    .from(positions)
    .where(and(eq(positions.marketId, marketId), eq(positions.memberId, memberId)));
  return p ? D(side === "YES" ? p.yes : p.no) : D(0);
}

/**
 * The share count for a percentage of what is held (the sell slider), rounded
 * down to 12 decimals. 100% is "all": exactly the shares held, nothing left over.
 */
export function sharesForPercent(percent: number, held: Dec): string {
  if (!Number.isInteger(percent) || percent < 1 || percent > 100) throw new UserError("Pourcentage invalide.");
  if (percent === 100) return "all";
  return held.mul(percent).div(100).toDecimalPlaces(SHARE_DECIMALS, Decimal.ROUND_DOWN).toString();
}

function parseShares(text: string, held: Dec): Dec {
  if (text === "all") return held;
  let s: Dec;
  try {
    s = D(text);
  } catch {
    throw new UserError("Nombre de parts invalide.");
  }
  if (!s.isFinite() || !s.gt(0) || s.decimalPlaces() > SHARE_DECIMALS) throw new UserError("Nombre de parts invalide.");
  return s;
}

/** Sells shares back to the pool at the current price. All or nothing. */
export async function sell(db: Db, memberId: string, input: SellInput, now: Date = new Date()): Promise<TradeResult> {
  return withReplay(db, input.requestId, memberId, "sell", async (tx) => {
    const m = await lockForTrade(tx, input.marketId, memberId);
    const done = await replayed(tx, input.requestId, memberId, "sell");
    if (done) return done;
    checkOpen(m, now);
    const held = await heldShares(tx, m.id, memberId, input.side);
    const shares = parseShares(input.shares, held);
    if (!held.gt(0) || shares.gt(held)) throw new UserError("Tu n'as pas ces parts.");

    let q;
    try {
      q = quoteSell(poolOf(m), input.side, shares);
    } catch {
      throw new UserError("Cette vente est trop petite pour valoir 0,01 pièce.");
    }
    await tx.insert(trades).values({
      marketId: m.id,
      memberId,
      side: input.side,
      kind: "sell",
      coins: q.proceeds,
      shares: shares.toFixed(SHARE_DECIMALS),
      probBefore: q.probBefore.toFixed(12),
      probAfter: q.probAfter.toFixed(12),
      requestId: input.requestId,
    });
    await tx.insert(ledger).values({ memberId, amount: q.proceeds, reason: "sale", marketId: m.id, requestId: input.requestId });
    await tx
      .update(markets)
      .set({ poolYes: q.pool.yes.toFixed(SHARE_DECIMALS), poolNo: q.pool.no.toFixed(SHARE_DECIMALS) })
      .where(eq(markets.id, m.id));
    return { shares, coins: q.proceeds, percentAfter: displayPercent(q.pool) };
  });
}

async function currentPool(db: Db, marketId: string): Promise<Pool> {
  const [m] = await db.select({ poolYes: markets.poolYes, poolNo: markets.poolNo }).from(markets).where(eq(markets.id, marketId));
  if (!m) throw new UserError("Marché introuvable.");
  return poolOf(m);
}

/**
 * What the confirm sheet shows before a bet. A preview only: the price can
 * move before the bet is confirmed. A win pays at least 1 coin per share,
 * more if the crowd loses coins to the pool (decision 007).
 */
export async function quoteBuyFor(db: Db, marketId: string, side: Side, coins: Coins) {
  if (coins < MIN_BET) throw new UserError("La mise minimum est de 1 pièce.");
  try {
    const q = quoteBuy(await currentPool(db, marketId), side, coins);
    return { shares: q.shares, percentAfter: displayPercent(q.pool), payoutAtLeast: decimalToCoinsDown(q.shares) };
  } catch (err) {
    if (err instanceof UserError) throw err;
    throw new UserError("Ce pari est trop gros pour ce marché.");
  }
}

/** What the confirm sheet shows before a sale. */
export async function quoteSellFor(db: Db, marketId: string, memberId: string, side: Side, sharesText: string) {
  const held = await heldShares(db, marketId, memberId, side);
  const shares = parseShares(sharesText, held);
  if (!held.gt(0) || shares.gt(held)) throw new UserError("Tu n'as pas ces parts.");
  try {
    const q = quoteSell(await currentPool(db, marketId), side, shares);
    return { shares, proceeds: q.proceeds, percentAfter: displayPercent(q.pool), held };
  } catch {
    throw new UserError("Cette vente est trop petite pour valoir 0,01 pièce.");
  }
}
